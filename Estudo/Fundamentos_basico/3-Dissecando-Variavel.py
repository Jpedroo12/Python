a = input('Digite Algo: ')
'''Vê o tipo primitivo da variável'''
print ('O tipo é primitivo desse valor é ', type(a))
'''Verica se tem somente espaços'''
print ('Só tem espaços? ', a.isspace())
'''Verica se é numérico'''
print ('É um número? ', a.isnumeric())
'''Verifica se é alfa'''
print ('É alfabético? ', a.isalpha())
'''Verifica se é alfanumérico'''
print ('É alfanumérico? ', a.isalnum())
'''Verifica se está em maiúsculas'''
print ('Está em maiúusculas? ', a.isupper())
'''Verifica se está em minúsculas'''
print ('Está em minúsculas? ', a.islower())
'''EX: NOme, EscolA'''
print ('Está capitalizada? ', a.istitle())


